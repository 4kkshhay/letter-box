"""Admin password hashing, signed sessions and login throttling."""

import base64
import hashlib
import hmac
import secrets
import time
from collections import deque
from getpass import getpass
from threading import Lock

PASSWORD_SCHEME = "scrypt"
SCRYPT_N = 2**14
SCRYPT_R = 8
SCRYPT_P = 1
SALT_BYTES = 16
HASH_BYTES = 32

SESSION_COOKIE = "letterbox_session"
SESSION_LIFETIME_SECONDS = 12 * 60 * 60


def _encode(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode("ascii")


def _decode(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def hash_password(password: str, *, salt: bytes | None = None) -> str:
    """Return a self-contained scrypt password hash for `.env`."""
    if not password:
        raise ValueError("Password must not be empty")
    salt = salt or secrets.token_bytes(SALT_BYTES)
    digest = hashlib.scrypt(
        password.encode("utf-8"), salt=salt, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P, dklen=HASH_BYTES
    )
    return f"{PASSWORD_SCHEME}${SCRYPT_N}${SCRYPT_R}${SCRYPT_P}${_encode(salt)}${_encode(digest)}"


def verify_password(password: str, encoded: str) -> bool:
    """Verify only the bounded hash format generated by `hash_password`."""
    try:
        scheme, n, r, p, salt, expected = encoded.split("$")
        if (scheme, int(n), int(r), int(p)) != (
            PASSWORD_SCHEME,
            SCRYPT_N,
            SCRYPT_R,
            SCRYPT_P,
        ):
            return False
        actual = hashlib.scrypt(
            password.encode("utf-8"),
            salt=_decode(salt),
            n=SCRYPT_N,
            r=SCRYPT_R,
            p=SCRYPT_P,
            dklen=HASH_BYTES,
        )
        return hmac.compare_digest(actual, _decode(expected))
    except (ValueError, TypeError):
        return False


def password_hash_configured(encoded: str) -> bool:
    """Whether a setting has the complete bounded scrypt hash shape."""
    try:
        scheme, n, r, p, salt, digest = encoded.split("$")
        return (
            (scheme, int(n), int(r), int(p))
            == (PASSWORD_SCHEME, SCRYPT_N, SCRYPT_R, SCRYPT_P)
            and len(_decode(salt)) == SALT_BYTES
            and len(_decode(digest)) == HASH_BYTES
        )
    except (ValueError, TypeError):
        return False


def create_session(secret: str, *, issued_at: int | None = None) -> str:
    issued_at = int(time.time()) if issued_at is None else issued_at
    payload = f"v1:{issued_at}"
    signature = hmac.new(secret.encode("utf-8"), payload.encode("ascii"), hashlib.sha256).digest()
    return f"{payload}.{_encode(signature)}"


def valid_session(value: str | None, secret: str, *, now: int | None = None) -> bool:
    if not value or not secret:
        return False
    try:
        payload, signature = value.rsplit(".", 1)
        version, issued = payload.split(":", 1)
        issued_at = int(issued)
        current = int(time.time()) if now is None else now
        expected = hmac.new(
            secret.encode("utf-8"), payload.encode("ascii"), hashlib.sha256
        ).digest()
        return (
            version == "v1"
            and 0 <= current - issued_at <= SESSION_LIFETIME_SECONDS
            and hmac.compare_digest(expected, _decode(signature))
        )
    except (ValueError, TypeError):
        return False


class LoginThrottle:
    """Small global limiter suitable for this single-admin app."""

    def __init__(self, *, attempts: int = 5, window_seconds: int = 5 * 60) -> None:
        self.attempts = attempts
        self.window_seconds = window_seconds
        self._failures: deque[float] = deque()
        self._lock = Lock()

    def _discard_old(self, now: float) -> None:
        while self._failures and now - self._failures[0] >= self.window_seconds:
            self._failures.popleft()

    def allowed(self) -> bool:
        with self._lock:
            self._discard_old(time.monotonic())
            return len(self._failures) < self.attempts

    def failed(self) -> None:
        with self._lock:
            now = time.monotonic()
            self._discard_old(now)
            self._failures.append(now)

    def reset(self) -> None:
        with self._lock:
            self._failures.clear()


def main() -> None:
    """Interactive entry point used by scripts/hash-admin-password.sh."""
    password = getpass("Admin password: ")
    if password != getpass("Confirm password: "):
        raise SystemExit("Passwords did not match")
    try:
        # Single quotes keep the `$` separators literal in Compose `.env` parsing.
        print(f"ADMIN_PASSWORD_HASH='{hash_password(password)}'")
    except ValueError as error:
        raise SystemExit(str(error)) from None


if __name__ == "__main__":
    main()
